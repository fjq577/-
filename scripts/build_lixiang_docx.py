def _east_asia_font(rPr, name="仿宋_GB2312", size_pt=12):
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.insert(0, rFonts)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)
    rFonts.set(qn("w:eastAsia"), name)
    rFonts.set(qn("w:cs"), name)
    sz = OxmlElement("w:sz")
    sz.set(qn("w:val"), str(int(size_pt * 2)))
    rPr.append(sz)
    szCs = OxmlElement("w:szCs")
    szCs.set(qn("w:val"), str(int(size_pt * 2)))
    rPr.append(szCs)


def _run_text(text: str, size_pt=12, bold=False):
    r = OxmlElement("w:r")
    rPr = OxmlElement("w:rPr")
    _east_asia_font(rPr, size_pt=size_pt)
    if bold:
        b = OxmlElement("w:b")
        rPr.append(b)
        bCs = OxmlElement("w:bCs")
        rPr.append(bCs)
    r.append(rPr)
    t = OxmlElement("w:t")
    t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    t.text = text
    r.append(t)
    return r


def _rev_wrap(kind: str, text: str, size_pt=12, bold=False):
    wrapper = OxmlElement("w:ins" if kind == "ins" else "w:del")
    wrapper.set(qn("w:id"), _nid())
    wrapper.set(qn("w:author"), AUTHOR)
    wrapper.set(qn("w:date"), REV_DATE)
    r = OxmlElement("w:r")
    rPr = OxmlElement("w:rPr")
    _east_asia_font(rPr, size_pt=size_pt)
    if bold:
        b = OxmlElement("w:b")
        rPr.append(b)
    r.append(rPr)
    if kind == "ins":
        t = OxmlElement("w:t")
        t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
        t.text = text
        r.append(t)
    else:
        t = OxmlElement("w:delText")
        t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
        t.text = text
        r.append(t)
    wrapper.append(r)
    return wrapper


def add_mixed(p, parts, size_pt=12, bold=False, first_indent=True):
    """parts: list of ('t'|'d'|'i', text)."""
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.space_after = Pt(4)
    if first_indent:
        pf.first_line_indent = Cm(0.74)
    pPr = p._p.get_or_add_pPr()
    rPr_def = pPr.find(qn("w:rPr"))
    if rPr_def is None:
        rPr_def = OxmlElement("w:rPr")
        pPr.append(rPr_def)
    _east_asia_font(rPr_def, size_pt=size_pt)
    for kind, text in parts:
        if not text:
            continue
        if kind == "t":
            p._p.append(_run_text(text, size_pt=size_pt, bold=bold))
        else:
            p._p.append(_rev_wrap("ins" if kind == "i" else "del", text, size_pt=size_pt, bold=bold))


def P(doc, parts, *, size_pt=12, bold=False, indent=True, align=None):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    add_mixed(p, parts, size_pt=size_pt, bold=bold, first_indent=indent)
    return p


def H(doc, text, size=16):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(8)
    add_mixed(p, [("t", text)], size_pt=size, bold=True, first_indent=False)


def SH(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(6)
    add_mixed(p, [("t", text)], size_pt=14, bold=True, first_indent=False)


def set_cell_text(cell, parts, size=10.5):
    cell.text = ""
    p = cell.paragraphs[0]
    add_mixed(p, parts, size_pt=size, bold=False, first_indent=False)


def add_table(doc, header, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(header))
    table.style = "Table Grid"
    for i, h in enumerate(header):
        set_cell_text(table.rows[0].cells[i], [("t", h)], size=10)
        for rp in table.rows[0].cells[i].paragraphs:
            for r in rp.runs:
                r.bold = True
    for r_i, row in enumerate(rows):
        for c_i, cell_parts in enumerate(row):
            set_cell_text(table.rows[r_i + 1].cells[c_i], cell_parts, size=10)
    doc.add_paragraph()
    return table


def replace_pair(old, new):
    return [("d", old), ("i", new)]



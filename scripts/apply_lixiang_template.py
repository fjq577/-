def _copy_rpr(src_r):
    if src_r is None:
        return None
    rPr = src_r.find(qn("w:rPr"))
    return deepcopy(rPr) if rPr is not None else None


def _make_run(text: str, rPr=None, *, deleted=False, highlight=False):
    r = OxmlElement("w:r")
    pr = deepcopy(rPr) if rPr is not None else OxmlElement("w:rPr")
    if pr is None:
        pr = OxmlElement("w:rPr")
    existing = pr.find(qn("w:highlight"))
    if existing is not None:
        pr.remove(existing)
    if highlight:
        hl = OxmlElement("w:highlight")
        hl.set(qn("w:val"), "yellow")
        pr.append(hl)
    r.append(pr)
    t = OxmlElement("w:delText" if deleted else "w:t")
    t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    t.text = text
    r.append(t)
    return r


def _ins_runs(text: str, rPr=None):
    wrapper = OxmlElement("w:ins")
    wrapper.set(qn("w:id"), nid())
    wrapper.set(qn("w:author"), AUTHOR)
    wrapper.set(qn("w:date"), REV_DATE)
    if BLANK not in text:
        wrapper.append(_make_run(text, rPr))
        return wrapper
    segs = text.split(BLANK)
    for i, seg in enumerate(segs):
        if seg:
            wrapper.append(_make_run(seg, rPr))
        if i < len(segs) - 1:
            wrapper.append(_make_run(BLANK, rPr, highlight=True))
    return wrapper


def revise_p(p, new_text: str) -> None:
    """整段删除旧文、插入新文，保留段落属性。"""
    elm = p._p
    old = "".join(elm.itertext())
    # python-docx paragraph.text is cleaner
    old_txt = p.text
    if old_txt == new_text:
        return
    first_r = elm.find(qn("w:r"))
    rPr = _copy_rpr(first_r)
    children = [c for c in list(elm) if c.tag != qn("w:pPr")]
    if children:
        dwrap = OxmlElement("w:del")
        dwrap.set(qn("w:id"), nid())
        dwrap.set(qn("w:author"), AUTHOR)
        dwrap.set(qn("w:date"), REV_DATE)
        for c in children:
            elm.remove(c)
            if c.tag == qn("w:r"):
                for t in c.findall(qn("w:t")):
                    t.tag = qn("w:delText")
                dwrap.append(c)
            else:
                dwrap.append(c)
        elm.append(dwrap)
    else:
        dwrap = OxmlElement("w:del")
        dwrap.set(qn("w:id"), nid())
        dwrap.set(qn("w:author"), AUTHOR)
        dwrap.set(qn("w:date"), REV_DATE)
        dwrap.append(_make_run(old_txt or old, rPr, deleted=True))
        elm.append(dwrap)
    elm.append(_ins_runs(new_text, rPr))


def revise_cell(cell, new_text: str) -> None:
    if not cell.paragraphs:
        cell.text = new_text
        return
    revise_p(cell.paragraphs[0], new_text)
    for extra in cell.paragraphs[1:]:
        extra.text = ""


def revise_tc(tc, new_text: str) -> None:
    """按实际 w:tc 改第一段，避免合并单元格被 python-docx 重复映射。"""
    ps = tc.findall(qn("w:p"))
    if not ps:
        p = OxmlElement("w:p")
        tc.append(p)
        ps = [p]
    class _P:
        def __init__(self, elm):
            self._p = elm

        @property
        def text(self):
            return "".join(self._p.itertext())

    revise_p(_P(ps[0]), new_text)


def insert_column(table, index: int):
    tbl = table._tbl
    grid = tbl.find(qn("w:tblGrid"))
    cols = grid.findall(qn("w:gridCol"))
    sample = deepcopy(cols[min(index, len(cols) - 1)])
    grid.insert(list(grid).index(cols[min(index, len(cols) - 1)]), sample)
    for tr in tbl.findall(qn("w:tr")):
        tcs = tr.findall(qn("w:tc"))
        pos = min(index, len(tcs))
        src = tcs[min(pos, len(tcs) - 1)]
        new_tc = deepcopy(src)
        # 清空文字
        for t in new_tc.findall(".//" + qn("w:t")):
            t.text = ""
        for t in new_tc.findall(".//" + qn("w:delText")):
            t.text = ""
        tr.insert(list(tr).index(tcs[pos]) if pos < len(tcs) else len(list(tr)), new_tc)


def add_table_row(table):
    tbl = table._tbl
    rows = tbl.findall(qn("w:tr"))
    new_tr = deepcopy(rows[-1])
    for t in new_tr.findall(".//" + qn("w:t")):
        t.text = ""
    tbl.append(new_tr)


